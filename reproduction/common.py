"""Shared, dependency-light helpers for the reviewer reproduction scripts.

The experiment drivers intentionally live outside ``src/``, ``applications/``,
and ``advanced/``.  They call the paper code as subprocesses and keep every
generated artifact below a caller-selected output directory.
"""

