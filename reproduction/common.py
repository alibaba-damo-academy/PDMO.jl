def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _capture(command: Sequence[str], cwd: Path | None = None) -> str | None:
    try:
        result = subprocess.run(
            command,
            cwd=cwd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def _json_safe(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, (tuple, list)):
        return [_json_safe(item) for item in value]
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    return value


def write_provenance(
    output: Path,
    *,
    section: str,
    args: argparse.Namespace,
    jobs: Sequence[Job] = (),
    inputs: Sequence[Path] = (),
    notes: Sequence[str] = (),
) -> Path:
    git_commit = _capture(("git", "rev-parse", "HEAD"), REPO_ROOT)
    git_status = _capture(("git", "status", "--short"), REPO_ROOT)
    julia_version = (
        _capture((args.julia, "--version"))
        if args.mode in ("smoke", "full", "reported")
        else None
    )
    input_records = []
    for path in inputs:
        expanded = path.expanduser().resolve()
        record: dict[str, Any] = {"path": str(expanded), "exists": expanded.exists()}
        if expanded.is_file():
            record["size_bytes"] = expanded.stat().st_size
            record["sha256"] = sha256_file(expanded)
        input_records.append(record)
    payload = {
        "section": section,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "arguments": _json_safe(vars(args)),
        "repository": {
            "path": str(REPO_ROOT),
            "git_commit": git_commit,
            "git_status_short": git_status,
        },
        "runtime": {
            "python": sys.version,
            "julia": julia_version,
            "platform": platform.platform(),
            "machine": platform.machine(),
            "processor": platform.processor(),
            "cpu_count": os.cpu_count(),
        },
        "inputs": input_records,
        "jobs": [{"name": job.name, "command": list(job.command)} for job in jobs],
        "notes": list(notes),
    }
    path = output / "provenance.json"
    write_json(path, payload)
    return path


def job_results_as_dicts(results: Sequence[JobResult]) -> list[dict[str, Any]]:
    return [asdict(result) for result in results]
