def _resolve_python(value: Path | None) -> str:
    candidate = str(value) if value is not None else os.environ.get("PDMO_PYTHON", "")
    if not candidate:
        raise SystemExit(
            "Fresh GNN runs require PDMO_PYTHON. Pass --python /path/to/python "
            "or export PDMO_PYTHON before running."
        )
    expanded = Path(candidate).expanduser()
    if expanded.is_file():
        return str(expanded.resolve())
    resolved = shutil.which(candidate)
    if resolved:
        return resolved
    raise SystemExit(f"Python executable not found: {candidate}")


def _check_python_dependencies(executable: str) -> None:
    version_command = (
        executable,
        "-c",
        "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')",
    )
    try:
        version_result = subprocess.run(
            version_command,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise SystemExit(f"Could not query Python environment {executable}: {error}") from error
    version_text = version_result.stdout.strip()
    try:
        version = tuple(int(value) for value in version_text.split("."))
    except ValueError as error:
        raise SystemExit(
            f"Could not parse Python version from {executable}: {version_text!r}"
        ) from error
    if version_result.returncode != 0 or len(version) != 2:
        raise SystemExit(
            f"Could not query Python version from {executable}: {version_text!r}"
        )
    if not ((3, 9) <= version < (3, 12)):
        raise SystemExit(
            "Fresh GNN runs require Python 3.9-3.11 "
            f"(selected {version_text}: {executable}). Python 3.12 is rejected "
            "because the current PyCall/Torch path can crash during interpreter finalization. "
            "Python 3.9 matches the archived experiment environment."
        )

    command = (
        executable,
        "-c",
        "import numpy, torch, torch_geometric; "
        "print(torch.__version__, torch_geometric.__version__, numpy.__version__)",
    )
    try:
        completed = subprocess.run(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
            timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise SystemExit(f"Could not validate GNN Python environment {executable}: {error}") from error
    if completed.returncode != 0:
        raise SystemExit(
            "The selected Python cannot import numpy, torch, and torch_geometric:\n"
            f"{completed.stdout.strip()}"
        )
    print(f"GNN Python environment: {completed.stdout.strip()}")


def _check_pycall_dependencies(julia: str, executable: str) -> None:
    script = REPRODUCTION_ROOT / "julia" / "check_pycall.jl"
    command = julia_command(julia, 1, script, executable)
    child_env, _ = _sanitize_julia_environment(os.environ)
    child_env["PDMO_PYTHON"] = executable
    try:
        completed = subprocess.run(
            command,
            cwd=REPO_ROOT,
            env=child_env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
            timeout=300,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise SystemExit(f"Could not validate Julia PyCall environment: {error}") from error
    if completed.returncode != 0:
        raise SystemExit(
            "The advanced Julia environment cannot use the selected GNN Python. "
            "Set PDMO_PYTHON and rerun advanced/warmup.jl, then retry:\n"
            f"{completed.stdout.strip()}"
        )
    print(completed.stdout.strip())


def _matpower_inputs(directory: Path, specs: Sequence[ExperimentSpec]) -> dict[str, Path]:
    directory = directory.expanduser().resolve()
    if not directory.is_dir():
        raise SystemExit(f"MATPOWER directory not found: {directory}")
    cases = tuple(dict.fromkeys(spec.case for spec in specs))
    inputs = {case: directory / f"{case}.m" for case in cases}
    missing = [path for path in inputs.values() if not path.is_file()]
    if missing:
        formatted = "\n".join(f"  - {path}" for path in missing)
        raise SystemExit(f"Required MATPOWER case files are missing:\n{formatted}")
    mismatched = []
    for case, path in inputs.items():
        observed = sha256_file(path)
        expected = MATPOWER_8_1_SHA256[case]
        if observed != expected:
            mismatched.append(f"{path}: expected {expected}, observed {observed}")
    if mismatched:
        formatted = "\n".join(f"  - {item}" for item in mismatched)
        raise SystemExit(
            "MATPOWER inputs do not match the pinned 8.1 paper files:\n" + formatted
        )
    return inputs


def _jobs_for_specs(
    args: argparse.Namespace,
    specs: Sequence[ExperimentSpec],
    case_files: Mapping[str, Path],
) -> list[Job]:
    runner = REPO_ROOT / "advanced" / "src" / "OPF" / "runDistributedOPF.jl"
    if not runner.is_file():
        raise SystemExit(f"Existing DC-OPF runner not found: {runner}")
    jobs: list[Job] = []
    for spec in specs:
        # All defaults are passed explicitly so later source-default changes cannot
        # silently alter the reviewer experiment.
        command = julia_command(
            args.julia,
            args.threads,
            runner,
            case_files[spec.case],
            spec.partition_number,
            spec.solver,
            f"{spec.rho:.1f}",
            f"{TOLERANCE:.1e}",
            MAX_ITERATIONS,
            f"{TIME_LIMIT_SECONDS:.1f}",
            LOG_INTERVAL,
            f"{R_VALUE:.1f}",
            SEED,
        )
        jobs.append(Job(spec.job_name, command))
    return jobs


