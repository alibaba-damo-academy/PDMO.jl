def _match_required(pattern: str, text: str, label: str, path: Path) -> str:
    match = re.search(pattern, text, flags=re.MULTILINE)
    if not match:
        raise ValueError(f"{path}: missing {label}")
    return match.group(1).strip()


def _optional_float(pattern: str, text: str) -> float | str:
    match = re.search(pattern, text, flags=re.MULTILINE)
    return float(match.group(1)) if match else ""


def _detailed_results(text: str) -> list[dict[str, object]]:
    label_map = {
        "Objective": "objective",
        "Pres (L2)": "pres_l2",
        "Pres (LInf)": "pres_linf",
        "Dres (L2)": "dres_l2",
        "Dres (LInf)": "dres_linf",
        "Stop. Iter": "iterations",
        "Total Time": "total_time",
        "True Obj. Diff": "true_obj_diff",
    }
    results: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    for line in text.splitlines():
        status_match = re.search(r"Solver Status\s*=\s*(\S+)", line)
        if status_match:
            if current is not None:
                results.append(current)
            current = {"status": status_match.group(1)}
            continue
        if current is None or "=" not in line:
            continue
        label, value = (part.strip() for part in line.split("=", 1))
        field = label_map.get(label)
        if field is None:
            continue
        token = value.split()[0]
        try:
            current[field] = int(token) if field == "iterations" else float(token)
        except ValueError:
            continue
    if current is not None:
        results.append(current)
    return results[-3:]


def _classify_spec(
    case: str, partition_number: int, solver: str, rho: float
) -> ExperimentSpec:
    if solver == "original" and math.isclose(rho, 100.0):
        key = (13, case, partition_number)
        candidates = FRESH_SPEC_BY_KEY
    elif solver == "doubly" and math.isclose(rho, 1000.0):
        key = (14, case, partition_number)
        candidates = FRESH_SPEC_BY_KEY
    elif solver == "doubly" and math.isclose(rho, 2000.0):
        key = (14, case, partition_number)
        candidates = ARCHIVED_SPEC_BY_KEY
    else:
        raise ValueError(
            f"unsupported Section 3.3 configuration case={case}, P={partition_number}, "
            f"solver={solver}, rho={rho}"
        )
    try:
        return candidates[key]
    except KeyError as error:
        raise ValueError(
            f"configuration is not in the Figure 13/14 paper grid: case={case}, "
            f"P={partition_number}, solver={solver}, rho={rho}"
        ) from error


def _parse_log(path: Path) -> tuple[ExperimentSpec, list[dict[str, object]]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    summary_matches = list(
        re.finditer(r"SUMMARY OF RESULTS for partitions:\s*(\d+)", text)
    )
    if not summary_matches:
        raise ValueError(f"{path}: missing final SUMMARY OF RESULTS table")
    summary_match = summary_matches[-1]
    partition_number = int(summary_match.group(1))
    invocation_start = text.rfind("Running Distributed DCOPF", 0, summary_match.start())
    if invocation_start < 0:
        raise ValueError(f"{path}: missing Running Distributed DCOPF header")
    invocation = text[invocation_start:]
    pre_summary = text[invocation_start : summary_match.start()]
    summary = text[summary_match.start() :]

    case_file = _match_required(
        r"^\s*case file\s*=\s*(.+?)\s*$", invocation, "case file", path
    )
    case = Path(case_file).stem
    header_partition = int(
        _match_required(
            r"^\s*num\. Partitions\s*=\s*(\d+)\s*$",
            invocation,
            "partition count",
            path,
        )
    )
    if header_partition != partition_number:
        raise ValueError(
            f"{path}: header partition {header_partition} disagrees with summary {partition_number}"
        )
    solver = _match_required(
        r"^\s*admmSolver\s*=\s*(\S+)\s*$", invocation, "ADMM solver", path
    )
    rho = float(
        _match_required(
            r"^\s*initialRho\s*=\s*([-+0-9.eE]+)\s*$",
            invocation,
            "initial rho",
            path,
        )
    )
    spec = _classify_spec(case, partition_number, solver, rho)

    config: dict[str, object] = {
        "figure": spec.figure,
        "case": case,
        "partition_number": partition_number,
        "case_file": case_file,
        "admm_solver": solver,
        "initial_rho": rho,
        "tolerance": float(
            _match_required(
                r"^\s*tol\s*=\s*([-+0-9.eE]+)\s*$", invocation, "tolerance", path
            )
        ),
        "max_iterations": int(
            _match_required(
                r"^\s*maxIter\s*=\s*(\d+)\s*$", invocation, "maximum iterations", path
            )
        ),
        "time_limit_seconds": float(
            _match_required(
                r"^\s*timeLimit\s*=\s*([-+0-9.eE]+)\s*$",
                invocation,
                "time limit",
                path,
            )
        ),
        "log_interval": int(
            _match_required(
                r"^\s*logInterval\s*=\s*(\d+)\s*$", invocation, "log interval", path
            )
        ),
        "r_value": float(
            _match_required(
                r"^\s*r_value\s*=\s*([-+0-9.eE]+)\s*$", invocation, "r_value", path
            )
        ),
        "seed": int(
            _match_required(r"^\s*seed\s*=\s*(\d+)\s*$", invocation, "seed", path)
        ),
        "threads": int(
            _match_required(
                r"Run Bipartite ADMM with threads\s*=\s*(\d+)",
                invocation,
                "Julia thread count",
                path,
            )
        ),
        "true_dc_objective": float(
            _match_required(
                r"True DC objective:\s*([-+0-9.eE]+)",
                invocation,
                "centralized DC objective",
                path,
            )
        ),
        "log_path": str(path.resolve()),
    }

    details = _detailed_results(pre_summary)
    detail_by_method = {
        method: details[index] if index < len(details) else {}
        for index, method in enumerate(METHODS)
    }
    summary_pattern = re.compile(
        r"^\s*(BFS|MILP|GNN)\s*\|\s*([-+0-9.eE]+)\s*\|\s*(\d+)\s*\|"
        r"\s*([-+0-9.eE]+)\s*\|\s*([-+0-9.eE]+)\s*\|",
        flags=re.MULTILINE,
    )
    summary_rows: dict[str, tuple[float, int, float, float]] = {}
    for match in summary_pattern.finditer(summary):
        summary_rows[match.group(1)] = (
            float(match.group(2)),
            int(match.group(3)),
            float(match.group(4)),
            float(match.group(5)),
        )
    missing_methods = [method for method in METHODS if method not in summary_rows]
    if missing_methods:
        raise ValueError(f"{path}: final summary is missing methods {missing_methods}")

    rows: list[dict[str, object]] = []
    for method in METHODS:
        partition_time, iterations, admm_time, admm_objective = summary_rows[method]
        detail = detail_by_method[method]
        detail_iterations = detail.get("iterations")
        if detail_iterations not in (None, iterations):
            raise ValueError(
                f"{path}: {method} detailed iterations {detail_iterations} "
                f"disagree with summary {iterations}"
            )
        row = dict(config)
        row.update(
            {
                "method": method,
                "partition_time_seconds": partition_time,
                "admm_time_seconds": admm_time,
                "total_time_seconds": partition_time + admm_time,
                "iterations": iterations,
                "admm_objective": admm_objective,
                "termination_status": detail.get("status", ""),
                "primal_residual_l2": detail.get("pres_l2", ""),
                "primal_residual_linf": detail.get("pres_linf", ""),
                "dual_residual_l2": detail.get("dres_l2", ""),
                "dual_residual_linf": detail.get("dres_linf", ""),
                "true_objective_difference": detail.get("true_obj_diff", ""),
            }
        )
        rows.append(row)
    return spec, rows


def _parse_logs(paths: Iterable[Path]) -> tuple[list[ExperimentSpec], list[dict[str, object]]]:
    specs: list[ExperimentSpec] = []
    rows: list[dict[str, object]] = []
    errors: list[str] = []
    for path in paths:
        try:
            spec, parsed = _parse_log(path)
        except (OSError, ValueError) as error:
            errors.append(str(error))
            continue
        specs.append(spec)
        rows.extend(parsed)
    if errors:
        formatted = "\n".join(f"  - {error}" for error in errors)
        raise SystemExit(f"Failed to parse Section 3.3 logs:\n{formatted}")
    if not rows:
        raise SystemExit("No complete Section 3.3 DC-OPF logs were found")
    return specs, rows


def _close(left: float, right: float) -> bool:
    return math.isclose(left, right, rel_tol=1.0e-10, abs_tol=1.0e-12)


def _validate_rows(
    rows: Sequence[Mapping[str, object]],
    expected_specs: Sequence[ExperimentSpec],
    *,
    require_archived_statuses: bool,
    check_objectives: bool,
) -> dict[str, object]:
    expected_jobs = {spec.key for spec in expected_specs}
    grouped: dict[tuple[int, str, int], list[Mapping[str, object]]] = defaultdict(list)
    for row in rows:
        key = (int(row["figure"]), str(row["case"]), int(row["partition_number"]))
        grouped[key].append(row)
    actual_jobs = set(grouped)
    errors: list[str] = []
    if actual_jobs != expected_jobs:
        missing = sorted(expected_jobs - actual_jobs)
        extra = sorted(actual_jobs - expected_jobs)
        errors.append(f"Unexpected Section 3.3 job grid; missing={missing}, extra={extra}")

    for spec in expected_specs:
        job_rows = grouped.get(spec.key)
        if job_rows is None:
            continue
        method_counts = Counter(str(row["method"]) for row in job_rows)
        if method_counts != Counter(METHODS):
            errors.append(f"{spec.key}: method rows are {dict(method_counts)}")
            continue
        for row in job_rows:
            method = str(row["method"])
            checks = (
                (str(row["admm_solver"]) == spec.solver, "solver"),
                (_close(float(row["initial_rho"]), spec.rho), "rho"),
                (_close(float(row["tolerance"]), TOLERANCE), "tolerance"),
                (int(row["max_iterations"]) == MAX_ITERATIONS, "max iterations"),
                (_close(float(row["time_limit_seconds"]), TIME_LIMIT_SECONDS), "time limit"),
                (int(row["log_interval"]) == LOG_INTERVAL, "log interval"),
                (_close(float(row["r_value"]), R_VALUE), "r_value"),
                (int(row["seed"]) == SEED, "seed"),
                (float(row["partition_time_seconds"]) >= 0.0, "partition time"),
                (float(row["admm_time_seconds"]) >= 0.0, "ADMM time"),
                (int(row["iterations"]) > 0, "iterations"),
            )
            for passed, label in checks:
                if not passed:
                    errors.append(f"{spec.key}/{method}: invalid {label}: {row.get(label, '')}")

            status = str(row["termination_status"])
            if status not in {
                "ADMM_TERMINATION_OPTIMAL",
                "ADMM_TERMINATION_TIME_LIMIT",
            }:
                errors.append(f"{spec.key}/{method}: unexpected status {status}")

            if check_objectives:
                expected_objective = OBJECTIVE_FINGERPRINTS[spec.case]
                observed_objective = float(row["true_dc_objective"])
                if not math.isclose(
                    observed_objective, expected_objective, rel_tol=1.0e-8, abs_tol=1.0e-4
                ):
                    errors.append(
                        f"{spec.key}/{method}: centralized objective {observed_objective:.12g} "
                        f"does not match MATPOWER fingerprint {expected_objective:.12g}"
                    )

            if require_archived_statuses:
                expected_status = (
                    "ADMM_TERMINATION_TIME_LIMIT"
                    if spec.figure == 13
                    and spec.case == "case1888rte"
                    and spec.partition_number == 10
                    else "ADMM_TERMINATION_OPTIMAL"
                )
                if status != expected_status:
                    errors.append(
                        f"{spec.key}/{method}: archived status {status!r}, expected {expected_status}"
                    )

    status_counts = Counter(
        str(row["termination_status"]) or "UNKNOWN" for row in rows
    )
    return {
        "status": "passed" if not errors else "failed",
        "expected_job_count": len(expected_jobs),
        "actual_job_count": len(actual_jobs),
        "row_count": len(rows),
        "expected_method_count_per_job": len(METHODS),
        "expected_methods": list(METHODS),
        "require_archived_statuses": require_archived_statuses,
        "check_objective_fingerprints": check_objectives,
        "experiment_profile": _experiment_profile(expected_specs),
        "termination_status_counts": dict(sorted(status_counts.items())),
        "missing_jobs": [list(key) for key in sorted(expected_jobs - actual_jobs)],
        "unexpected_jobs": [list(key) for key in sorted(actual_jobs - expected_jobs)],
        "errors": errors,
        "warnings": [],
    }


def _aggregate(rows: Sequence[Mapping[str, object]]) -> list[dict[str, object]]:
    by_case_method: dict[tuple[str, str], list[Mapping[str, object]]] = defaultdict(list)
    by_partition_method: dict[tuple[int, str], list[Mapping[str, object]]] = defaultdict(list)
    for row in rows:
        if int(row["figure"]) == 13:
            by_case_method[(str(row["case"]), str(row["method"]))].append(row)
        else:
            by_partition_method[(int(row["partition_number"]), str(row["method"]))].append(row)

    aggregates: list[dict[str, object]] = []
    for case in FIGURE_13_CASES:
        if not any(key[0] == case for key in by_case_method):
            continue
        for method in METHODS:
            selected = by_case_method[(case, method)]
            aggregates.append(
                {
                    "figure": 13,
                    "case": case,
                    "partition_number": "",
                    "aggregation": "arithmetic_mean_over_partitions",
                    "method": method,
                    "sample_count": len(selected),
                    "partition_time_seconds": arithmetic_mean(
                        float(row["partition_time_seconds"]) for row in selected
                    ),
                    "admm_time_seconds": arithmetic_mean(
                        float(row["admm_time_seconds"]) for row in selected
                    ),
                    "iterations": arithmetic_mean(float(row["iterations"]) for row in selected),
                }
            )
    for partition_number in FIGURE_14_PARTITIONS:
        if not any(key[0] == partition_number for key in by_partition_method):
            continue
        for method in METHODS:
            selected = by_partition_method[(partition_number, method)]
            aggregates.append(
                {
                    "figure": 14,
                    "case": "case57",
                    "partition_number": partition_number,
                    "aggregation": "per_partition",
                    "method": method,
                    "sample_count": len(selected),
                    "partition_time_seconds": arithmetic_mean(
                        float(row["partition_time_seconds"]) for row in selected
                    ),
                    "admm_time_seconds": arithmetic_mean(
                        float(row["admm_time_seconds"]) for row in selected
                    ),
                    "iterations": arithmetic_mean(float(row["iterations"]) for row in selected),
                }
            )

    normalization_groups: dict[tuple[int, str, object], list[dict[str, object]]] = defaultdict(list)
    for aggregate in aggregates:
        partition_key: object = (
            aggregate["partition_number"] if int(aggregate["figure"]) == 14 else "mean"
        )
        normalization_groups[
            (int(aggregate["figure"]), str(aggregate["case"]), partition_key)
        ].append(aggregate)
    for selected in normalization_groups.values():
        for aggregate in selected:
            aggregate["total_time_seconds"] = float(aggregate["partition_time_seconds"]) + float(
                aggregate["admm_time_seconds"]
            )
        max_time = max(float(aggregate["total_time_seconds"]) for aggregate in selected)
        max_iterations = max(float(aggregate["iterations"]) for aggregate in selected)
        for aggregate in selected:
            aggregate["normalized_partition_time"] = (
                float(aggregate["partition_time_seconds"]) / max_time if max_time > 0 else 0.0
            )
            aggregate["normalized_admm_time"] = (
                float(aggregate["admm_time_seconds"]) / max_time if max_time > 0 else 0.0
            )
            aggregate["normalized_total_time"] = (
                float(aggregate["total_time_seconds"]) / max_time if max_time > 0 else 0.0
            )
            aggregate["normalized_iterations"] = (
                float(aggregate["iterations"]) / max_iterations if max_iterations > 0 else 0.0
            )
    return aggregates


def _aggregate_index(
    rows: Sequence[Mapping[str, object]],
) -> dict[tuple[int, str, int | None, str], Mapping[str, object]]:
    result = {}
    for row in rows:
        partition = int(row["partition_number"]) if row["partition_number"] != "" else None
        result[(int(row["figure"]), str(row["case"]), partition, str(row["method"]))] = row
    return result


def _draw_iterations(axis, groups: Sequence[object], labels: Sequence[str], values) -> None:
    width = 0.25
    x_positions = list(range(len(groups)))
    offsets = {"BFS": -width, "MILP": 0.0, "GNN": width}
    for method in METHODS:
        axis.bar(
            [position + offsets[method] for position in x_positions],
            [values(group, method) for group in groups],
            width=width,
            color=METHOD_COLORS[method],
            label=method,
        )
    axis.set_xticks(x_positions)
    axis.set_xticklabels(labels)
    axis.set_ylabel("Normalized iterations", fontsize=13)
    axis.set_ylim(0.0, 1.08)
    axis.grid(axis="y", alpha=0.22)
    axis.legend(ncol=3, fontsize=11)


def _draw_time(axis, groups: Sequence[object], labels: Sequence[str], values) -> None:
    width = 0.25
    x_positions = list(range(len(groups)))
    offsets = {"BFS": -width, "MILP": 0.0, "GNN": width}
    for method in METHODS:
        positions = [position + offsets[method] for position in x_positions]
        partition_values = [values(group, method, "normalized_partition_time") for group in groups]
        admm_values = [values(group, method, "normalized_admm_time") for group in groups]
        axis.bar(
            positions,
            partition_values,
            width=width,
            color=METHOD_LIGHT_COLORS[method],
        )
        axis.bar(
            positions,
            admm_values,
            width=width,
            bottom=partition_values,
            color=METHOD_COLORS[method],
            label=method,
        )
    axis.set_xticks(x_positions)
    axis.set_xticklabels(labels)
    axis.set_ylabel("Normalized time", fontsize=13)
    axis.set_ylim(0.0, 1.08)
    axis.grid(axis="y", alpha=0.22)
    axis.legend(ncol=3, fontsize=11)


