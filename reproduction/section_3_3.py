def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    validate_common_arguments(args)
    output = prepare_mode_output(args.output, args.mode)

    fresh = args.mode in ("smoke", "full")
    if args.mode == "smoke":
        expected_specs = SMOKE_SPECS
    elif args.mode == "archived":
        expected_specs = ARCHIVED_SPECS
    else:
        expected_specs = FRESH_FULL_SPECS
    jobs: list[Job] = []
    job_results = []
    provenance_inputs: list[Path] = []
    fresh_log_paths: list[Path] = []
    reported_panel_validation: dict[str, object] | None = None

    if fresh:
        case_files = _matpower_inputs(args.matpower_dir, expected_specs)
        python_executable = _resolve_python(args.pdmo_python)
        _check_python_dependencies(python_executable)
        _check_pycall_dependencies(args.julia, python_executable)
        model_weights = REPO_ROOT / "advanced" / "src" / "gnn" / "GNN" / "model_weights_10.pth"
        if not model_weights.is_file():
            raise SystemExit(f"Bundled GNN weights not found: {model_weights}")
        jobs = _jobs_for_specs(args, expected_specs, case_files)
        if args.mode == "full":
            print(
                "Full Section 3.3 sweep: archived partition+ADMM time is about 34.1 hours "
                "with one worker; setup and compilation are additional.",
                flush=True,
            )
        job_results = run_jobs(
            jobs,
            log_root=output / "raw",
            cwd=legacy_workdir(),
            workers=args.jobs,
            resume=not args.no_resume,
            environment={"PDMO_PYTHON": python_executable},
        )
        write_json(output / "job_results.json", job_results_as_dicts(job_results))
        failures = failed_jobs(job_results)
        if failures:
            write_provenance(
                output,
                section="Section 3.3 / DC-OPF Figures 13-14",
                args=args,
                jobs=jobs,
                inputs=tuple(case_files.values()) + (model_weights,),
                notes=("One or more fresh Julia subprocesses failed; inspect job_results.json.",),
            )
            names = ", ".join(result.name for result in failures)
            raise SystemExit(f"Section 3.3 Julia jobs failed: {names}")
        fresh_log_paths = [Path(result.log_path) for result in job_results]
        provenance_inputs.extend(case_files.values())
        provenance_inputs.append(model_weights)
    elif args.mode == "archived":
        provenance_inputs.append(args.archive)

    if fresh:
        parsed_specs, rows = _parse_logs(fresh_log_paths)
    else:
        with source_logs(args, ARCHIVE_SECTION, output / "raw") as source:
            if args.mode == "archived":
                paths = _archived_final_logs(source)
                reported_panel_validation = _preserve_reported_figure_14_panels(
                    source, output
                )
                write_json(output / "reported_source_panels.json", reported_panel_validation)
            else:
                # If parse points at an extracted copy of the original archive,
                # use the same explicit final selection.  Otherwise parse the
                # caller's complete/smoke raw-log directory.
                try:
                    paths = _archived_final_logs(source)
                except SystemExit:
                    paths = collect_logs(source)
            parsed_specs, rows = _parse_logs(paths)
        if args.mode == "parse":
            expected_specs = _parse_mode_expected_specs(parsed_specs)

    experiment_profile = _experiment_profile(expected_specs)
    write_json(
        output / "experiment_profile.json",
        {"mode": args.mode, **experiment_profile},
    )
    artifact_scope = {
        "archived": "archived_reconstruction",
        "parse": "caller_supplied_parse_input",
        "smoke": "validation_only_subset",
        "full": "fresh_paper_grid",
    }[args.mode]
    if experiment_profile["classification"] == "historical_reported_archive":
        publication_warning = (
            "This reconstructs the published Figure 14 rho=2000 source profile; "
            "the manuscript caption instead states rho=1000."
        )
    elif args.mode == "smoke":
        publication_warning = (
            "Smoke artifacts validate one documented subset and are not complete paper figures."
        )
    else:
        publication_warning = (
            "This follows the manuscript-literal Figure 14 rho=1000 profile and is not "
            "the historical rho=2000 profile that generated the published panels."
        )
    write_json(
        output / "artifact_profile.json",
        {
            "mode": args.mode,
            "artifact_scope": artifact_scope,
            "publication_warning": publication_warning,
            "section_experiment_profile": experiment_profile,
        },
    )
    validation = _validate_rows(
        rows,
        expected_specs,
        require_archived_statuses=args.mode == "archived",
        check_objectives=fresh or args.mode == "archived",
    )
    if reported_panel_validation is not None:
        validation["reported_source_panel_validation"] = reported_panel_validation
        if reported_panel_validation["status"] != "passed":
            validation["errors"].extend(reported_panel_validation["errors"])
            validation["status"] = "failed"
    if validation["status"] != "passed":
        write_json(output / "validation.json", validation)
        formatted = "\n".join(f"  - {error}" for error in validation["errors"])
        raise SystemExit(f"Section 3.3 validation failed:\n{formatted}")
    if args.mode == "archived":
        for row in rows:
            row["log_path"] = _archive_log_identifier(args.archive, row)
    rows = sorted(
        rows,
        key=lambda row: (
            int(row["figure"]),
            FIGURE_13_CASES.index(str(row["case"]))
            if str(row["case"]) in FIGURE_13_CASES
            else 999,
            int(row["partition_number"]),
            METHODS.index(str(row["method"])),
        ),
    )
    aggregates = _aggregate(rows)
    write_csv(output / "runs.csv", RUN_FIELDS, rows)
    write_csv(output / "aggregates.csv", AGGREGATE_FIELDS, aggregates)

    smoke_keys = {spec.key for spec in SMOKE_SPECS}
    expected_keys = {spec.key for spec in expected_specs}
    smoke_profile = (
        len(expected_specs) == len(SMOKE_SPECS) and expected_keys == smoke_keys
    )
    comparison = _reference_comparison(
        aggregates,
        rows,
        smoke_profile=smoke_profile,
    )
    write_json(output / "reference_comparison.json", comparison)
    write_json(output / "runtime_summary.json", _runtime_summary(rows))
    validation = _merge_reference_validation(
        validation,
        comparison,
        mode=args.mode,
        smoke_profile=smoke_profile,
    )
    write_json(output / "validation.json", validation)
    if validation["status"] != "passed":
        formatted = "\n".join(f"  - {error}" for error in validation["errors"])
        raise SystemExit(f"Section 3.3 validation failed:\n{formatted}")

    if not args.no_plots:
        _plot_figure_13(aggregates, output)
        _plot_figure_14(aggregates, output)

    write_provenance(
        output,
        section="Section 3.3 / distributed DC-OPF Figures 13-14",
        args=args,
        jobs=jobs,
        inputs=provenance_inputs,
        notes=(
            "Figure 13: six MATPOWER cases, P=3:10, original ADMM, rho=100.",
            f"Experiment profile: {experiment_profile['classification']}.",
            (
                "Reported Figure 14: case57, P=13:18, doubly linearized ADMM, rho=2000, retained folder case57_flip_2000, jobs 51523865-51523870."
                if experiment_profile["classification"] == "historical_reported_archive"
                else "Fresh manuscript-literal Figure 14: case57, P=13:18, doubly linearized ADMM, rho=1000."
            ),
            "The manuscript caption says rho=1000; the exact retained source panels and their data use rho=2000.",
            (
                "Archived mode byte-preserves and SHA256-verifies both retained published Figure 14 source PNGs."
                if args.mode == "archived"
                else "Fresh/parse outputs remain separate from retained published source PNGs."
            ),
            "Fresh jobs use one Julia process per (case,P); BFS, MILP, and GNN share one METIS partition.",
            "Archived reported rho=2000 and fresh manuscript-literal rho=1000 profiles are never merged.",
            "The archived full sweep contains three valid time-limited method results at case1888rte/P=10.",
            "Reported archived partition+ADMM time is approximately 33.0 hours sequentially, excluding setup.",
        ),
    )
    print(f"Wrote Section 3.3 artifacts to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
