def _preserve_reported_figure_14_panels(
    section_root: Path, output: Path
) -> dict[str, object]:
    source_root = section_root / "case57_flip_2000"
    target_root = output / "reported_source"
    target_root.mkdir(parents=True, exist_ok=True)
    errors: list[str] = []
    panels: list[dict[str, object]] = []
    for source_name, (target_name, expected_sha256) in PUBLISHED_FIGURE_14_SOURCE_PANELS.items():
        source = source_root / source_name
        target = target_root / target_name
        record: dict[str, object] = {
            "source": str(source),
            "output": str(target),
            "expected_sha256": expected_sha256,
            "exists": source.is_file(),
        }
        if not source.is_file():
            errors.append(f"Missing retained published Figure 14 panel: {source}")
            record["hash_matches"] = False
        else:
            source_sha256 = sha256_file(source)
            record["source_sha256"] = source_sha256
            if source_sha256 != expected_sha256:
                errors.append(
                    f"{source_name} SHA256 {source_sha256} does not match {expected_sha256}"
                )
                record["hash_matches"] = False
            else:
                shutil.copy2(source, target)
                output_sha256 = sha256_file(target)
                record["output_sha256"] = output_sha256
                record["hash_matches"] = output_sha256 == expected_sha256
                if output_sha256 != expected_sha256:
                    errors.append(f"Copied retained panel hash mismatch: {target}")
        panels.append(record)
    return {
        "status": "passed" if not errors else "failed",
        "classification": "byte_exact_reported_source_preservation",
        "figure_14_profile": REPORTED_FIGURE_14_PROFILE,
        "errors": errors,
        "panels": panels,
    }


