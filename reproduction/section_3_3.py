def _smoke_reference_comparison(
    rows: Sequence[Mapping[str, object]],
) -> dict[str, object]:
    selected = {
        str(row["method"]): row
        for row in rows
        if int(row["figure"]) == 13
        and str(row["case"]) == "case30"
        and int(row["partition_number"]) == 3
    }
    reference_max_iterations = max(
        float(value["iterations"]) for value in REFERENCE_SMOKE_CASE30_P3.values()
    )
    reference_max_time = max(
        float(value["partition_time_seconds"]) + float(value["admm_time_seconds"])
        for value in REFERENCE_SMOKE_CASE30_P3.values()
    )
    observed_max_iterations = max(
        (float(row["iterations"]) for row in selected.values()),
        default=1.0,
    )
    observed_max_time = max(
        (float(row["total_time_seconds"]) for row in selected.values()),
        default=1.0,
    )

    entries: list[dict[str, object]] = []
    for method in METHODS:
        observed = selected.get(method)
        if observed is None:
            continue
        reference = REFERENCE_SMOKE_CASE30_P3[method]
        reference_iterations = float(reference["iterations"])
        reference_partition = float(reference["partition_time_seconds"])
        reference_admm = float(reference["admm_time_seconds"])
        reference_total = reference_partition + reference_admm
        observed_iterations = float(observed["iterations"])
        observed_partition = float(observed["partition_time_seconds"])
        observed_admm = float(observed["admm_time_seconds"])
        observed_total = float(observed["total_time_seconds"])
        entries.append(
            {
                "figure": 13,
                "case": "case30",
                "partition_number": 3,
                "method": method,
                "observed_iterations": observed_iterations,
                "reference_iterations": reference_iterations,
                "iterations_difference": observed_iterations - reference_iterations,
                "observed_partition_time_seconds": observed_partition,
                "reference_partition_time_seconds": reference_partition,
                "observed_admm_time_seconds": observed_admm,
                "reference_admm_time_seconds": reference_admm,
                "observed_total_time_seconds": observed_total,
                "reference_total_time_seconds": reference_total,
                "total_time_difference_seconds": observed_total - reference_total,
                "observed_normalized_iterations": observed_iterations
                / observed_max_iterations,
                "reference_normalized_iterations": reference_iterations
                / reference_max_iterations,
                "observed_normalized_total_time": observed_total / observed_max_time,
                "reference_normalized_total_time": reference_total / reference_max_time,
            }
        )

    status_counts = Counter(str(row["termination_status"]) or "UNKNOWN" for row in rows)
    max_iteration_difference = max(
        (abs(float(entry["iterations_difference"])) for entry in entries),
        default=0.0,
    )
    max_normalized_iteration_difference = max(
        (
            abs(
                float(entry["observed_normalized_iterations"])
                - float(entry["reference_normalized_iterations"])
            )
            for entry in entries
        ),
        default=0.0,
    )
    return {
        "reference": (
            "experiments_logs.zip Section 3.3 case30/P=3 raw result "
            "(case30/51455118)"
        ),
        "notes": [
            "This is the exact archived point selected by --mode smoke, not the Figure 13 mean over P=3,...,10.",
            "Iteration counts are the primary deterministic comparison.",
            "Runtime is hardware- and environment-dependent and is reported without pass/fail gating.",
        ],
        "summary": {
            "compared_entries": len(entries),
            "all_iteration_values_match": max_iteration_difference <= 1.0e-9,
            "maximum_absolute_iteration_difference": max_iteration_difference,
            "maximum_absolute_normalized_iteration_difference": max_normalized_iteration_difference,
            "termination_status_counts": dict(sorted(status_counts.items())),
        },
        "entries": entries,
    }


def _reference_comparison(
    aggregates: Sequence[Mapping[str, object]],
    rows: Sequence[Mapping[str, object]],
    *,
    smoke_profile: bool = False,
) -> dict[str, object]:
    if smoke_profile:
        return _smoke_reference_comparison(rows)

    index = _aggregate_index(aggregates)
    entries: list[dict[str, object]] = []

    for case, method_values in REFERENCE_FIGURE_13.items():
        reference_max_iterations = max(value[0] for value in method_values.values())
        reference_max_time = max(value[1] for value in method_values.values())
        for method in METHODS:
            key = (13, case, None, method)
            if key not in index:
                continue
            observed = index[key]
            reference_iterations, reference_time = method_values[method]
            entry = {
                "figure": 13,
                "case": case,
                "partition_number": None,
                "method": method,
                "observed_iterations": float(observed["iterations"]),
                "reference_iterations": reference_iterations,
                "iterations_difference": float(observed["iterations"]) - reference_iterations,
                "observed_total_time_seconds": float(observed["total_time_seconds"]),
                "reference_total_time_seconds": reference_time,
                "total_time_difference_seconds": float(observed["total_time_seconds"])
                - reference_time,
                "observed_normalized_iterations": float(observed["normalized_iterations"]),
                "reference_normalized_iterations": reference_iterations
                / reference_max_iterations,
                "observed_normalized_total_time": float(observed["normalized_total_time"]),
                "reference_normalized_total_time": reference_time / reference_max_time,
            }
            entries.append(entry)

    for partition_number, method_values in REFERENCE_FIGURE_14.items():
        reference_max_iterations = max(value[0] for value in method_values.values())
        reference_max_time = max(value[1] + value[2] for value in method_values.values())
        for method in METHODS:
            key = (14, "case57", partition_number, method)
            if key not in index:
                continue
            observed = index[key]
            reference_iterations, reference_partition, reference_admm = method_values[method]
            reference_time = reference_partition + reference_admm
            entries.append(
                {
                    "figure": 14,
                    "case": "case57",
                    "partition_number": partition_number,
                    "method": method,
                    "reference_initial_rho": 2000.0,
                    "observed_iterations": float(observed["iterations"]),
                    "reference_iterations": reference_iterations,
                    "iterations_difference": float(observed["iterations"])
                    - reference_iterations,
                    "observed_partition_time_seconds": float(observed["partition_time_seconds"]),
                    "reference_partition_time_seconds": reference_partition,
                    "observed_admm_time_seconds": float(observed["admm_time_seconds"]),
                    "reference_admm_time_seconds": reference_admm,
                    "observed_total_time_seconds": float(observed["total_time_seconds"]),
                    "reference_total_time_seconds": reference_time,
                    "total_time_difference_seconds": float(observed["total_time_seconds"])
                    - reference_time,
                    "observed_normalized_iterations": float(observed["normalized_iterations"]),
                    "reference_normalized_iterations": reference_iterations
                    / reference_max_iterations,
                    "observed_normalized_total_time": float(observed["normalized_total_time"]),
                    "reference_normalized_total_time": reference_time / reference_max_time,
                }
            )

    status_counts = Counter(str(row["termination_status"]) or "UNKNOWN" for row in rows)
    max_iteration_difference = max(
        (abs(float(entry["iterations_difference"])) for entry in entries), default=0.0
    )
    max_normalized_iteration_difference = max(
        (
            abs(
                float(entry["observed_normalized_iterations"])
                - float(entry["reference_normalized_iterations"])
            )
            for entry in entries
        ),
        default=0.0,
    )
    figure_14_entries = [entry for entry in entries if int(entry["figure"]) == 14]
    observed_figure_14_rhos = sorted(
        {
            float(row["initial_rho"])
            for row in rows
            if int(row["figure"]) == 14
        }
    )
    figure_14_reference_applicable = observed_figure_14_rhos == [2000.0]
    max_figure_14_iteration_difference = max(
        (abs(float(entry["iterations_difference"])) for entry in figure_14_entries),
        default=0.0,
    )
    max_figure_14_partition_time_difference = max(
        (
            abs(
                float(entry["observed_partition_time_seconds"])
                - float(entry["reference_partition_time_seconds"])
            )
            for entry in figure_14_entries
        ),
        default=0.0,
    )
    max_figure_14_admm_time_difference = max(
        (
            abs(
                float(entry["observed_admm_time_seconds"])
                - float(entry["reference_admm_time_seconds"])
            )
            for entry in figure_14_entries
        ),
        default=0.0,
    )
    all_figure_14_reference_values_match = (
        figure_14_reference_applicable
        and len(figure_14_entries) == len(FIGURE_14_PARTITIONS) * len(METHODS)
        and max_figure_14_iteration_difference <= 1.0e-9
        and max_figure_14_partition_time_difference <= 1.0e-9
        and max_figure_14_admm_time_difference <= 1.0e-9
    )
    return {
        "reference": "experiments_logs.zip final Section 3.3 folders used for paper Figures 13-14",
        "figure_14_reference_profile": REPORTED_FIGURE_14_PROFILE,
        "observed_figure_14_rhos": observed_figure_14_rhos,
        "figure_14_reference_applicable": figure_14_reference_applicable,
        "notes": [
            "Iteration counts are the primary deterministic comparison.",
            "Runtime is hardware- and environment-dependent and is reported without pass/fail gating.",
            "The archived case1888rte/P=10 runs hit the 7200-second limit for all methods.",
            "Figure 14 references are the exact retained rho=2000 values behind the published arXiv panels.",
            "They are explicitly not applicable to a fresh manuscript-literal rho=1000 Figure 14 run.",
        ],
        "summary": {
            "compared_entries": len(entries),
            "all_iteration_values_match": max_iteration_difference <= 1.0e-9,
            "maximum_absolute_iteration_difference": max_iteration_difference,
            "maximum_absolute_normalized_iteration_difference": max_normalized_iteration_difference,
            "figure_14_reference_applicable": figure_14_reference_applicable,
            "all_figure_14_reference_values_match": all_figure_14_reference_values_match,
            "maximum_absolute_figure_14_iteration_difference": max_figure_14_iteration_difference,
            "maximum_absolute_figure_14_partition_time_difference_seconds": max_figure_14_partition_time_difference,
            "maximum_absolute_figure_14_admm_time_difference_seconds": max_figure_14_admm_time_difference,
            "termination_status_counts": dict(sorted(status_counts.items())),
        },
        "entries": entries,
    }


def _reference_validation_errors(
    comparison: Mapping[str, object],
    *,
    mode: str,
    smoke_profile: bool,
) -> list[str]:
    summary = comparison.get("summary")
    if not isinstance(summary, Mapping):
        return ["Section 3.3 reference comparison has no valid summary"]
    errors: list[str] = []
    if (mode == "archived" or smoke_profile) and not bool(
        summary.get("all_iteration_values_match")
    ):
        profile = "archived grid" if mode == "archived" else "case30/P=3 smoke point"
        errors.append(
            f"Section 3.3 {profile} iteration values do not match embedded references"
        )
    if mode == "archived" and summary.get("figure_14_reference_applicable") is False:
        errors.append(
            "Archived Figure 14 data do not use the required historical rho=2000 profile"
        )
    if mode == "archived" and summary.get("all_figure_14_reference_values_match") is False:
        errors.append(
            "Archived Figure 14 iterations or component times do not match published references"
        )
    return errors


def _merge_reference_validation(
    validation: Mapping[str, object],
    comparison: Mapping[str, object],
    *,
    mode: str,
    smoke_profile: bool,
) -> dict[str, object]:
    """Return the final report after deterministic reference validation."""

    merged = dict(validation)
    errors = list(validation.get("errors", ()))
    errors.extend(
        _reference_validation_errors(
            comparison,
            mode=mode,
            smoke_profile=smoke_profile,
        )
    )
    merged["errors"] = errors
    merged["status"] = "passed" if not errors else "failed"
    merged["reference_summary"] = comparison.get("summary")
    return merged


def _enforce_iteration_reference(
    comparison: Mapping[str, object],
    *,
    mode: str,
    smoke_profile: bool,
) -> None:
    """Compatibility wrapper used by callers that want an immediate failure."""

    errors = _reference_validation_errors(
        comparison,
        mode=mode,
        smoke_profile=smoke_profile,
    )
    if errors:
        raise SystemExit(errors[0])


def _runtime_summary(rows: Sequence[Mapping[str, object]]) -> dict[str, object]:
    by_figure: dict[int, float] = defaultdict(float)
    by_case: dict[str, float] = defaultdict(float)
    for row in rows:
        total = float(row["total_time_seconds"])
        by_figure[int(row["figure"])] += total
        by_case[str(row["case"])] += total
    total = sum(by_figure.values())
    return {
        "measured_partition_plus_admm_seconds": total,
        "measured_partition_plus_admm_hours": total / 3600.0,
        "by_figure_seconds": {str(key): value for key, value in sorted(by_figure.items())},
        "by_case_seconds": dict(sorted(by_case.items())),
        "reported_rho2000_archive_full_sweep_seconds": 118954.649,
        "reported_rho2000_archive_full_sweep_hours": 118954.649 / 3600.0,
        "rho1000_retained_comparison_sweep_seconds": 122889.742,
        "rho1000_retained_comparison_sweep_hours": 122889.742 / 3600.0,
        "scope_note": (
            "Times sum only bipartization and ADMM times reported by the driver; dependency "
            "installation, compilation, centralized Ipopt solve, and process startup are excluded."
        ),
    }


def _spec_signature(spec: ExperimentSpec) -> tuple[int, str, int, str, float]:
    return (*spec.key, spec.solver, spec.rho)


def _parse_mode_expected_specs(
    specs: Sequence[ExperimentSpec],
) -> tuple[ExperimentSpec, ...]:
    actual = {_spec_signature(spec) for spec in specs}
    profiles = (SMOKE_SPECS, FRESH_FULL_SPECS, ARCHIVED_SPECS)
    for expected in profiles:
        expected_signatures = {_spec_signature(spec) for spec in expected}
        if len(specs) == len(expected) and actual == expected_signatures:
            return expected

    fresh = {_spec_signature(spec) for spec in FRESH_FULL_SPECS}
    missing = sorted(fresh - actual)
    extra = sorted(actual - fresh)
    raise SystemExit(
        "--mode parse expects the documented smoke grid, the fresh manuscript-literal "
        "rho=1000 full grid, or the reported archived rho=2000 full grid; "
        f"missing_from_fresh_full={missing}, extra_or_profile_mismatch={extra}"
    )


