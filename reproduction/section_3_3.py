@dataclass(frozen=True)
class ExperimentSpec:
    figure: int
    case: str
    partition_number: int
    solver: str
    rho: float
    archive_folder: str
    archive_job_id: str | None = None

    @property
    def key(self) -> tuple[int, str, int]:
        return (self.figure, self.case, self.partition_number)

    @property
    def job_name(self) -> str:
        return f"figure_{self.figure}/{self.case}/p{self.partition_number:02d}"


def _full_specs(
    *,
    figure_14_rho: float,
    figure_14_archive_folder: str,
    figure_14_job_ids: Sequence[str] | None,
) -> tuple[ExperimentSpec, ...]:
    specs: list[ExperimentSpec] = []
    for case in FIGURE_13_CASES:
        job_ids = ARCHIVED_JOB_IDS[case]
        for offset, partition_number in enumerate(FIGURE_13_PARTITIONS):
            specs.append(
                ExperimentSpec(
                    13,
                    case,
                    partition_number,
                    "original",
                    100.0,
                    case,
                    job_ids[offset],
                )
            )
    flip_ids = tuple(figure_14_job_ids or ())
    for offset, partition_number in enumerate(FIGURE_14_PARTITIONS):
        specs.append(
            ExperimentSpec(
                14,
                "case57",
                partition_number,
                "doubly",
                figure_14_rho,
                figure_14_archive_folder,
                flip_ids[offset] if flip_ids else None,
            )
        )
    return tuple(specs)


